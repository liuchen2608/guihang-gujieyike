import assert from "node:assert/strict";
import { localInviteClient, readTestCodes, redeemTestCode } from "./local-invite-client.mjs";

const origin = process.argv[2] || "http://localhost:3001";
const codes = readTestCodes(process.argv[3]);
const guest = localInviteClient(origin);
const saveId = crypto.randomUUID();
for (const [path, method] of [["/api/saves", "GET"], ["/api/saves", "POST"], [`/api/saves/${saveId}`, "GET"], [`/api/saves/${saveId}/turns`, "POST"], ["/api/feedback", "POST"]]) {
  const r = await guest.fetch(path, { method, ...(method === "POST" ? { headers: { "content-type": "application/json" }, body: "{}" } : {}) });
  assert.equal(r.status, 403, path);
  assert.equal((await r.json()).code, "INVITE_REQUIRED");
}
console.log("PASS all game APIs deny missing invitation before reading or acting");
const invalid = await redeemTestCode(guest, "GH-0000-0000-0000-0000-0000-0000");
assert.equal(invalid.status, 400);
const legacyPlayerId = crypto.randomUUID();
const first = await redeemTestCode(guest, codes[0].code, legacyPlayerId);
assert.equal(first.status, 200, await first.clone().text());
assert.equal((await first.json()).playerId, legacyPlayerId);
assert.match(first.headers.get("set-cookie"), /HttpOnly/i);
const retry = await redeemTestCode(guest, codes[0].code, legacyPlayerId);
assert.equal(retry.status, 200);
assert.equal((await (await guest.fetch("/api/access")).json()).authorized, true);
const foreign = localInviteClient(origin);
assert.equal((await redeemTestCode(foreign, codes[0].code)).status, 409);
console.log("PASS correct code, cookie persistence, retry idempotency, and one-use limit");
const create = await guest.fetch("/api/saves", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ playerId: "forged", codename: "邀请码验收" }) });
assert.equal(create.status, 201);
const save = await create.json();
assert.equal((await guest.fetch(`/api/saves/${save.state.saveId}?playerId=forged`)).status, 200);
assert.equal((await foreign.fetch(`/api/saves/${save.state.saveId}?playerId=${legacyPlayerId}`)).status, 403);
assert.equal((await redeemTestCode(foreign, codes[1].code)).status, 200);
assert.equal((await foreign.fetch(`/api/saves/${save.state.saveId}?playerId=${legacyPlayerId}`)).status, 404);
console.log("PASS server credential, not client playerId, determines save ownership");
const racers = [localInviteClient(origin), localInviteClient(origin)];
await Promise.all(racers.map(c => c.fetch("/api/access")));
const race = await Promise.all(racers.map(c => redeemTestCode(c, codes[2].code)));
assert.deepEqual(race.map(r => r.status).sort(), [200, 409]);
console.log("PASS concurrent browsers cannot over-redeem the same invitation");
const duplicate = localInviteClient(origin);
await duplicate.fetch("/api/access");
const duplicateRace = await Promise.all([0, 1].map(() => redeemTestCode(duplicate, codes[3].code)));
assert.deepEqual(duplicateRace.map(r => r.status), [200, 200]);
console.log("PASS repeated clicks in the same browser consume only one grant");
const limited = localInviteClient(origin, "127.0.0.2");
for (let i = 0; i < 5; i++) assert.equal((await redeemTestCode(limited, "GH-0000-0000-0000-0000-0000-0000")).status, 400);
assert.equal((await redeemTestCode(limited, codes[4].code)).status, 429);
console.log("PASS failed code attempts are limited without consuming an unused code");
const request = await fetch(new URL("/api/access/redeem", origin), { method: "POST", headers: { "content-type": "application/json", origin: "https://other.example" }, body: "{}" });
assert.equal(request.status, 403);
console.log("PASS cross-site redemption is rejected");
